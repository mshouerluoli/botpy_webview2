static const size_t HTTP_CLIENT_PY_LEN = sizeof(HTTP_CLIENT_PY);

class PythonHttpClient
{
public:
    PythonHttpClient(const std::string& pythonExe = "python")
        : m_pythonExe(pythonExe)
    {
 
        char tempFile[MAX_PATH];
        char tempPath[MAX_PATH];
        GetTempPathA(MAX_PATH, tempPath);
        GetTempFileNameA(tempPath, "py_", 0, tempFile);
        m_scriptPath = tempFile;


        std::ofstream ofs(m_scriptPath, std::ios::binary);
        if (ofs.is_open())
        {
            ofs.write(reinterpret_cast<const char*>(HTTP_CLIENT_PY), HTTP_CLIENT_PY_LEN);
            ofs.close();
        }
        else
        {
            throw std::runtime_error("Failed to create temporary Python script file");
        }
    }

    ~PythonHttpClient()
    {

        if (!m_scriptPath.empty())
        {
            DeleteFileA(m_scriptPath.c_str());
        }
    }


    bool SendRequest(
        const std::string& url,
        const std::string& method,
        const std::string& data,
        const std::map<std::string, std::string>& headers,
        int& statusCode,
        std::string& responseBody,
        std::string& errorMsg)
    {

        std::string requestJson = BuildRequestJson(url, method, data, headers);


        char inputFile[MAX_PATH];
        char outputFile[MAX_PATH];
        char tempPath[MAX_PATH];
        GetTempPathA(MAX_PATH, tempPath);
        GetTempFileNameA(tempPath, "hin", 0, inputFile);
        GetTempFileNameA(tempPath, "hout", 0, outputFile);


        {
            std::ofstream ofs(inputFile);
            if (!ofs.is_open())
            {
                errorMsg = "Failed to create input file";
                DeleteFileA(inputFile);
                DeleteFileA(outputFile);
                return false;
            }
            ofs << requestJson;
            ofs.close();
        }


        std::string cmd = "\"" + m_pythonExe + "\" \"" + m_scriptPath + "\" --input \"" + inputFile + "\" --output \"" + outputFile + "\"";


        std::string errors;
        bool success = ExecuteCommand(cmd, errors);

        if (!success)
        {
            errorMsg = "Failed to execute Python script: " + errors;
            DeleteFileA(inputFile);
            DeleteFileA(outputFile);
            return false;
        }

  
        std::string output;
        {
            std::ifstream ifs(outputFile);
            if (!ifs.is_open())
            {
                errorMsg = "Failed to read output file";
                DeleteFileA(inputFile);
                DeleteFileA(outputFile);
                return false;
            }
            std::ostringstream ss;
            ss << ifs.rdbuf();
            output = ss.str();
            ifs.close();
        }

        DeleteFileA(inputFile);
        DeleteFileA(outputFile);


        if (ParseJsonResponse(output, statusCode, responseBody, errorMsg))
        {
            return true;
        }
        else
        {
            errorMsg = "Failed to parse Python output: " + output;
            return false;
        }
    }


    bool Get(const std::string& url,
        const std::map<std::string, std::string>& headers,
        int& statusCode,
        std::string& responseBody,
        std::string& errorMsg)
    {
        return SendRequest(url, "GET", "", headers, statusCode, responseBody, errorMsg);
    }


    bool Post(const std::string& url,
        const std::string& data,
        const std::map<std::string, std::string>& headers,
        int& statusCode,
        std::string& responseBody,
        std::string& errorMsg)
    {
        return SendRequest(url, "POST", data, headers, statusCode, responseBody, errorMsg);
    }

private:
    std::string m_scriptPath;
    std::string m_pythonExe;


    std::string BuildRequestJson(const std::string& url, const std::string& method,
        const std::string& data, const std::map<std::string, std::string>& headers)
    {
        std::string json = "{";
        json += "\"url\":\"" + EscapeString(url) + "\",";
        json += "\"method\":\"" + EscapeString(method) + "\",";
        json += "\"data\":\"" + EscapeString(data) + "\",";

        json += "\"headers\":{";
        bool first = true;
        for (const auto& kv : headers)
        {
            if (!first) json += ",";
            json += "\"" + EscapeString(kv.first) + "\":\"" + EscapeString(kv.second) + "\"";
            first = false;
        }
        json += "}}";

        return json;
    }

    std::string EscapeString(const std::string& s)
    {
        std::string result;
        for (char c : s)
        {
            switch (c)
            {
            case '"': result += "\\\""; break;
            case '\\': result += "\\\\"; break;
            case '\n': result += "\\n"; break;
            case '\r': result += "\\r"; break;
            case '\t': result += "\\t"; break;
            default: result += c;
            }
        }
        return result;
    }


    bool ExecuteCommand(const std::string& cmd, std::string& errors)
    {
        SECURITY_ATTRIBUTES saAttr;
        saAttr.nLength = sizeof(SECURITY_ATTRIBUTES);
        saAttr.bInheritHandle = TRUE;
        saAttr.lpSecurityDescriptor = NULL;

        HANDLE hChildStd_ERR_Rd = NULL;
        HANDLE hChildStd_ERR_Wr = NULL;

        if (!CreatePipe(&hChildStd_ERR_Rd, &hChildStd_ERR_Wr, &saAttr, 0))
            return false;

        if (!SetHandleInformation(hChildStd_ERR_Rd, HANDLE_FLAG_INHERIT, 0))
        {
            CloseHandle(hChildStd_ERR_Rd);
            CloseHandle(hChildStd_ERR_Wr);
            return false;
        }

        STARTUPINFOA siStartInfo;
        ZeroMemory(&siStartInfo, sizeof(STARTUPINFOA));
        siStartInfo.cb = sizeof(STARTUPINFOA);
        siStartInfo.hStdError = hChildStd_ERR_Wr;
        siStartInfo.dwFlags |= STARTF_USESTDHANDLES | STARTF_USESHOWWINDOW;
        siStartInfo.wShowWindow = SW_HIDE;

        PROCESS_INFORMATION piProcInfo;
        ZeroMemory(&piProcInfo, sizeof(PROCESS_INFORMATION));

        std::string cmdBuffer = cmd;

        if (!CreateProcessA(
            NULL,
            const_cast<LPSTR>(cmdBuffer.c_str()),
            NULL, NULL, TRUE,
            CREATE_NO_WINDOW,
            NULL, NULL,
            &siStartInfo,
            &piProcInfo))
        {
            CloseHandle(hChildStd_ERR_Rd);
            CloseHandle(hChildStd_ERR_Wr);
            return false;
        }

        CloseHandle(hChildStd_ERR_Wr);


        DWORD dwRead;
        CHAR chBuf[4096];
        while (ReadFile(hChildStd_ERR_Rd, chBuf, sizeof(chBuf) - 1, &dwRead, NULL) && dwRead > 0)
        {
            chBuf[dwRead] = '\0';
            errors += chBuf;
        }

        WaitForSingleObject(piProcInfo.hProcess, 30000);

        CloseHandle(piProcInfo.hProcess);
        CloseHandle(piProcInfo.hThread);
        CloseHandle(hChildStd_ERR_Rd);

        return true;
    }


    bool ParseJsonResponse(const std::string& json, int& statusCode, std::string& body, std::string& errorMsg)
    {
 
        std::string cleanJson = json;
        size_t start = cleanJson.find_first_not_of(" \t\r\n");
        if (start == std::string::npos)
            return false;
        cleanJson = cleanJson.substr(start);
        size_t end = cleanJson.find_last_not_of(" \t\r\n");
        if (end != std::string::npos)
            cleanJson = cleanJson.substr(0, end + 1);

        size_t pos;
        pos = cleanJson.find("\"success\"");
        if (pos == std::string::npos)
            return false;

        pos = cleanJson.find(":", pos);
        if (pos == std::string::npos)
            return false;

        pos++;
        while (pos < cleanJson.size() && (cleanJson[pos] == ' ' || cleanJson[pos] == '\t')) pos++;

        bool success = false;
        if (pos < cleanJson.size() && cleanJson[pos] == 't')
            success = true;


        pos = cleanJson.find("\"status_code\"");
        if (pos == std::string::npos)
            return false;

        pos = cleanJson.find(":", pos);
        if (pos == std::string::npos)
            return false;

        pos++;
        while (pos < cleanJson.size() && (cleanJson[pos] == ' ' || cleanJson[pos] == '\t')) pos++;

        std::string numStr;
        while (pos < cleanJson.size() && (isdigit(cleanJson[pos]) || cleanJson[pos] == '-'))
        {
            numStr += cleanJson[pos];
            pos++;
        }

        statusCode = atoi(numStr.c_str());

        pos = cleanJson.find("\"body\"");
        if (pos != std::string::npos)
        {
            body = ExtractJsonString(cleanJson, pos);
        }
        else
        {
            body = "";
        }

        pos = cleanJson.find("\"error\"");
        if (pos != std::string::npos)
        {
            errorMsg = ExtractJsonString(cleanJson, pos);
        }
        else
        {
            errorMsg = "";
        }

        return success || !errorMsg.empty();
    }

    std::string ExtractJsonString(const std::string& json, size_t keyPos)
    {
        size_t pos = json.find(":", keyPos);
        if (pos == std::string::npos)
            return "";

        pos++;
        while (pos < json.size() && (json[pos] == ' ' || json[pos] == '\t')) pos++;

        if (pos >= json.size() || json[pos] != '"')
            return "";

        pos++;

        std::string result;
        while (pos < json.size() && json[pos] != '"')
        {
            if (json[pos] == '\\' && pos + 1 < json.size())
            {
                pos++;
                switch (json[pos])
                {
                case '"': result += '"'; break;
                case '\\': result += '\\'; break;
                case '/': result += '/'; break;
                case 'n': result += '\n'; break;
                case 'r': result += '\r'; break;
                case 't': result += '\t'; break;
                default: result += json[pos];
                }
            }
            else
            {
                result += json[pos];
            }
            pos++;
        }

        return result;
    }
};

